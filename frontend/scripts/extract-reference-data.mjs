// One-off extraction script — pulls the business-niche + targeting-content data
// out of "reference only.html" (repo root) into clean frontend source files,
// so the app never depends on that file at runtime. Run once, before the
// reference file is deleted:
//
//   node frontend/scripts/extract-reference-data.mjs
//
// The reference embeds several `const NAME = {...}` / `const NAME = [...]`
// blobs as valid JSON. We locate each by name, use a bracket-depth scanner
// (string-aware, so braces inside quoted text don't confuse it) to find
// where the literal ends, then JSON.parse it directly — no eval, no running
// the reference's own (browser-dependent) app code.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const REFERENCE_PATH = path.join(REPO_ROOT, "reference only.html");
const OUT_DIR = path.join(__dirname, "..", "src", "lib");

function extractConst(raw, name) {
  const marker = `const ${name} = `;
  const start = raw.indexOf(marker);
  if (start === -1) {
    throw new Error(`Could not find "${marker}" in the reference file — has its format changed?`);
  }
  const literalStart = start + marker.length;

  let depth = 0;
  let inString = false;
  let started = false;
  let end = -1;

  for (let i = literalStart; i < raw.length; i++) {
    const ch = raw[i];

    if (inString) {
      if (ch === "\\") { i++; continue; } // skip escaped char, incl. escaped quote
      if (ch === '"') inString = false;
      continue;
    }

    if (ch === '"') { inString = true; continue; }
    if (ch === "{" || ch === "[") { depth++; started = true; continue; }
    if (ch === "}" || ch === "]") {
      depth--;
      if (started && depth === 0) { end = i + 1; break; }
      continue;
    }
  }

  if (end === -1) {
    throw new Error(`Could not find the end of the "${name}" literal — bracket scanner did not close.`);
  }

  const literalText = raw.slice(literalStart, end);
  try {
    return JSON.parse(literalText);
  } catch (e) {
    throw new Error(`Failed to JSON.parse "${name}" (extracted ${literalText.length} chars): ${e.message}`);
  }
}

function main() {
  console.log(`Reading ${REFERENCE_PATH} ...`);
  const raw = fs.readFileSync(REFERENCE_PATH, "utf8");
  console.log(`  ${(raw.length / 1e6).toFixed(1)}MB read.`);

  const icData = extractConst(raw, "IC_DATA");
  const icAudience = extractConst(raw, "IC_AUDIENCE");
  const icBizAudience = extractConst(raw, "IC_BIZ_AUDIENCE");
  const cityMap = extractConst(raw, "CITY_MAP");

  // ---- Sanity checks ----
  const niches = icData.niches;
  if (!Array.isArray(niches)) throw new Error("IC_DATA.niches is not an array — format changed?");
  const categories = [...new Set(niches.map((n) => n.category))];
  console.log(`IC_DATA: ${niches.length} niches, ${categories.length} categories.`);
  if (niches.length !== 135) {
    throw new Error(`Expected 135 niches, got ${niches.length} — aborting, extraction may be wrong.`);
  }
  if (categories.length !== 13) {
    throw new Error(`Expected 13 categories, got ${categories.length} — aborting, extraction may be wrong.`);
  }

  // ---- Required content edit: Garage Door Repair -> Door Repairs ----
  const garageDoor = niches.find((n) => n.id === "garage-door-repair");
  if (!garageDoor) throw new Error('Could not find niche id "garage-door-repair" to rename.');
  garageDoor.name = "Door Repairs";
  console.log('Renamed "Garage Door Repair" -> "Door Repairs" (id unchanged).');

  // ---- Trim niches down to only the fields this feature uses ----
  const trimmedNiches = niches.map((n) => ({
    id: n.id,
    name: n.name,
    category: n.category,
    serves: n.serves,
  }));

  // ---- Write output files ----
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const businessNichesSrc = `// AUTO-GENERATED by frontend/scripts/extract-reference-data.mjs — do not hand-edit.
// Source: "reference only.html" (IC_DATA.niches), trimmed to the fields this
// feature uses. "Garage Door Repair" was renamed to "Door Repairs" per product
// decision; its id ("garage-door-repair") is unchanged so it still keys into
// audienceProfiles.js correctly.

export const BUSINESS_NICHES = ${JSON.stringify(trimmedNiches, null, 2)};

// First-appearance order, computed from the data (not hardcoded) so it always
// tracks BUSINESS_NICHES.
export const NICHE_CATEGORIES = [...new Set(BUSINESS_NICHES.map((n) => n.category))];
`;
  fs.writeFileSync(path.join(OUT_DIR, "businessNiches.js"), businessNichesSrc);
  console.log("Wrote src/lib/businessNiches.js");

  const audienceProfilesSrc = `// AUTO-GENERATED by frontend/scripts/extract-reference-data.mjs — do not hand-edit.
// Source: "reference only.html" (IC_AUDIENCE, IC_BIZ_AUDIENCE), keyed by
// business-niche id (see businessNiches.js). Full fidelity — every field here
// is rendered somewhere in the filter-stack module.

export const CONSUMER_AUDIENCE = ${JSON.stringify(icAudience, null, 2)};

export const BUSINESS_AUDIENCE = ${JSON.stringify(icBizAudience, null, 2)};
`;
  fs.writeFileSync(path.join(OUT_DIR, "audienceProfiles.js"), audienceProfilesSrc);
  console.log("Wrote src/lib/audienceProfiles.js");

  const cityMapSrc = `// AUTO-GENERATED by frontend/scripts/extract-reference-data.mjs — do not hand-edit.
// Source: "reference only.html" (CITY_MAP), keyed by full state name (matches
// usStates.js's US_STATES[].name, NOT the 2-letter abbreviation).

export const CITY_MAP = ${JSON.stringify(cityMap, null, 2)};
`;
  fs.writeFileSync(path.join(OUT_DIR, "cityMap.js"), cityMapSrc);
  console.log("Wrote src/lib/cityMap.js");

  const cityCount = Object.values(cityMap).reduce((sum, arr) => sum + arr.length, 0);
  console.log(`CITY_MAP: ${Object.keys(cityMap).length} states, ${cityCount} total cities.`);
  console.log("\nDone.");
}

main();
